export function findHubeiRegion(regionId: string): HubeiRegion | undefined {
  return hubeiRegions.find(region => region.id === regionId)
}

export function findHubeiPlace(regionId: string, placeId: string): HubeiRegion['keyPlaces'][number] | undefined {
  return findHubeiRegion(regionId)?.keyPlaces.find(place => place.id === placeId)
}

export function projectHubeiPoint(point: { lng: number; lat: number }): { x: number; y: number } {
  const x = ((point.lng - HUBEI_BBOX.minLng) / (HUBEI_BBOX.maxLng - HUBEI_BBOX.minLng)) * 100
  const y = ((HUBEI_BBOX.maxLat - point.lat) / (HUBEI_BBOX.maxLat - HUBEI_BBOX.minLat)) * 100
  return { x, y }
}
